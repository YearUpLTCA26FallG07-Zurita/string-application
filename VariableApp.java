package com.pluralsight;

public class VariableApp {
    public static void main(String[] args) {

        // Step 1:

        String color = "green";
        int year = 2026;
        char name = 'h';
        boolean pets = true;
        String message = "Have a wonderful day";

        System.out.println("Favorite color: " + color);
        System.out.println("Year I started YUU: " + year);
        System.out.println("My middle initial: " + name);
        System.out.println("Do I have pets? " + pets);
        System.out.println(message);

        // Step 2:

        int dayInWeek = 7;
        double price = 4.99;
        char favLetter = 'z';
        boolean isRaining = true;

        System.out.println("There are " + dayInWeek + "days in a week.");
        System.out.println("The price for a coffee is $" + price);
        System.out.println("My favorite letter is: " + favLetter);
        System.out.println("Is it raining? " + isRaining);

    }
}